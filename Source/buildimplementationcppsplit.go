// buildimplementationcppsplit.go
// Optional "split" output of the C++ implementation interfaces (see the -splitcpp flag):
//  - one interface header per class, plus an umbrella header with the original name
//  - new stubs include only the header of their own class
//////////////////////////////////////////////////////////////////////////////////////////////////////

package main

import (
	"fmt"
	"io"
	"log"
	"path"
	"strings"
)

func closeLanguageFile(w LanguageWriter) {
	if closer, ok := w.Writer.(io.Closer); ok {
		closer.Close()
	}
}

func cppSplitInterfaceHeaderName(BaseName string, ClassName string) string {
	return fmt.Sprintf("%s_interface_%s.hpp", BaseName, strings.ToLower(ClassName))
}

func createCppSplitFile(fileName string, indentString string, component ComponentDefinition, description string) (LanguageWriter, error) {
	log.Printf("Creating \"%s\"", fileName)
	file, err := CreateLanguageFile(fileName, indentString)
	if err != nil {
		return file, err
	}
	file.WriteCLicenseHeader(component, description, true)
	return file, nil
}

func buildCPPInterfacesSplit(component ComponentDefinition, outputFolder string, indentString string, NameSpaceImplementation string, ClassIdentifier string) error {
	NameSpace := component.NameSpace
	BaseName := component.BaseName
	upperNameSpace := strings.ToUpper(NameSpace)
	LibraryName := component.LibraryName

	// Forward declarations, shared by all class headers
	fwdFileName := BaseName + "_interfaces_fwd.hpp"
	w, err := createCppSplitFile(path.Join(outputFolder, fwdFileName), indentString, component,
		fmt.Sprintf("This is an autogenerated C++ header file with the forward declarations of the\ninterface classes of %s.", LibraryName))
	if err != nil {
		return err
	}
	w.Writeln("")
	w.Writeln("#ifndef __%s_CPPINTERFACES_FWD", upperNameSpace)
	w.Writeln("#define __%s_CPPINTERFACES_FWD", upperNameSpace)
	w.Writeln("")
	w.Writeln("#include <string>")
	w.Writeln("#include <memory>")
	if component.isMultiThreadedEnv() {
		w.Writeln("#include <mutex>")
	}
	w.Writeln("")
	w.Writeln("#include \"%s_types.hpp\"", BaseName)
	w.Writeln("")
	for _, subComponent := range component.ImportedComponentDefinitions {
		w.Writeln("#include \"%s_dynamic.hpp\"", subComponent.BaseName)
	}
	w.Writeln("")
	w.Writeln("namespace %s {", NameSpace)
	w.Writeln("namespace %s {", NameSpaceImplementation)
	w.Writeln("")
	w.Writeln("/**")
	w.Writeln(" Forward declarations of class interfaces")
	w.Writeln("*/")
	for _, class := range component.Classes {
		w.Writeln("class I%s%s;", ClassIdentifier, class.ClassName)
	}
	w.Writeln("")
	writeParameterCacheDefinitions(component, w, NameSpaceImplementation, ClassIdentifier)
	w.Writeln("")
	w.Writeln("} // namespace %s", NameSpaceImplementation)
	w.Writeln("} // namespace %s", NameSpace)
	w.Writeln("")
	w.Writeln("#endif // __%s_CPPINTERFACES_FWD", upperNameSpace)
	closeLanguageFile(w)

	// One header per class
	for _, class := range component.Classes {
		classHeaderName := cppSplitInterfaceHeaderName(BaseName, class.ClassName)
		w, err := createCppSplitFile(path.Join(outputFolder, classHeaderName), indentString, component,
			fmt.Sprintf("This is an autogenerated C++ header file with the interface of class %s of %s.", class.ClassName, LibraryName))
		if err != nil {
			return err
		}
		guard := fmt.Sprintf("__%s_CPPINTERFACE_%s", upperNameSpace, strings.ToUpper(class.ClassName))
		w.Writeln("")
		w.Writeln("#ifndef %s", guard)
		w.Writeln("#define %s", guard)
		w.Writeln("")
		w.Writeln("#include \"%s\"", fwdFileName)
		if !component.isBaseClass(class) {
			w.Writeln("#include \"%s\"", cppSplitInterfaceHeaderName(BaseName, class.ParentClass))
		}
		for _, returnedClassName := range cppSplitCovariantReturnClasses(component, class) {
			w.Writeln("#include \"%s\"", cppSplitInterfaceHeaderName(BaseName, returnedClassName))
		}
		w.Writeln("")
		w.Writeln("namespace %s {", NameSpace)
		w.Writeln("namespace %s {", NameSpaceImplementation)
		err = writeCPPClassInterface(component, class, w, NameSpace, NameSpaceImplementation, ClassIdentifier, BaseName)
		if err != nil {
			return err
		}
		w.Writeln("")
		w.Writeln("} // namespace %s", NameSpaceImplementation)
		w.Writeln("} // namespace %s", NameSpace)
		w.Writeln("")
		w.Writeln("#endif // %s", guard)
		closeLanguageFile(w)
	}

	// Umbrella header with the name of the monolithic header
	w, err = createCppSplitFile(path.Join(outputFolder, BaseName+"_interfaces.hpp"), indentString, component,
		fmt.Sprintf("This is an autogenerated C++ header file in order to allow easy\ndevelopment of %s. The implementer of %s needs to\nderive concrete classes from the abstract classes in the headers included here.", LibraryName, LibraryName))
	if err != nil {
		return err
	}
	w.Writeln("")
	w.Writeln("#ifndef __%s_CPPINTERFACES", upperNameSpace)
	w.Writeln("#define __%s_CPPINTERFACES", upperNameSpace)
	w.Writeln("")
	w.Writeln("#include \"%s\"", fwdFileName)
	for _, class := range component.Classes {
		w.Writeln("#include \"%s\"", cppSplitInterfaceHeaderName(BaseName, class.ClassName))
	}
	w.Writeln("")
	w.Writeln("namespace %s {", NameSpace)
	w.Writeln("namespace %s {", NameSpaceImplementation)
	err = writeCPPGlobalWrapperDeclaration(component, w, NameSpaceImplementation, ClassIdentifier)
	if err != nil {
		return err
	}
	w.Writeln("} // namespace %s", NameSpaceImplementation)
	w.Writeln("} // namespace %s", NameSpace)
	w.Writeln("")
	w.Writeln("#endif // __%s_CPPINTERFACES", upperNameSpace)
	closeLanguageFile(w)

	return nil
}

// cppSplitCovariantReturnClasses lists the classes returned by methods that override a method of an ancestor.
// C++ only accepts such covariant return types if the returned class is complete, so their headers must be included.
func cppSplitCovariantReturnClasses(component ComponentDefinition, class ComponentDefinitionClass) []string {
	ancestorMethodNames := make(map[string]bool)
	classesByName := make(map[string]ComponentDefinitionClass)
	for _, c := range component.Classes {
		classesByName[c.ClassName] = c
	}
	for current := class; !component.isBaseClass(current); {
		parent, found := classesByName[current.ParentClass]
		if !found {
			break
		}
		for _, method := range parent.Methods {
			ancestorMethodNames[strings.ToLower(method.MethodName)] = true
		}
		current = parent
	}

	result := make([]string, 0)
	seen := make(map[string]bool)
	for _, method := range class.Methods {
		if !ancestorMethodNames[strings.ToLower(method.MethodName)] {
			continue
		}
		for _, param := range method.Params {
			if param.ParamPass != "return" || (param.ParamType != "class" && param.ParamType != "optionalclass") {
				continue
			}
			className := param.ParamClass
			if _, known := classesByName[className]; known && className != class.ClassName && !seen[className] {
				seen[className] = true
				result = append(result, className)
			}
		}
	}
	return result
}
