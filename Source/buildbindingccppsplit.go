//////////////////////////////////////////////////////////////////////////////////////////////////////
// buildbindingccppsplit.go
// The "split" variant of the dynamic C++ binding (splitclasses="true" on a <binding language="CppDynamic"> element).
//
// The default binding puts everything into <basename>_dynamic.hpp. In the split variant
//  - the public headers only declare the classes (one header per class, <basename>_dynamic.hpp includes all of them),
//  - the method bodies, the function table, the library loading and the polymorphic factory are generated into
//    one source file that is compiled once, so a change of one class only affects the files using that class.
//////////////////////////////////////////////////////////////////////////////////////////////////////

package main

import (
	"fmt"
	"path"
	"strings"
)

func cppSplitBindingClassHeaderName(BaseName string, ClassName string) string {
	return fmt.Sprintf("%s_dynamic_%s.hpp", BaseName, strings.ToLower(ClassName))
}

func writeSplitNamespaceOpen(w LanguageWriter, NameSpace string) {
	w.Writeln("namespace %s {", NameSpace)
	w.Writeln("")
}

func writeSplitNamespaceClose(w LanguageWriter, NameSpace string) {
	w.Writeln("")
	w.Writeln("} // namespace %s", NameSpace)
	w.Writeln("")
}
// BuildBindingCppSplit generates the split variant of the dynamic C++ binding into outputFolder.
func BuildBindingCppSplit(component ComponentDefinition, outputFolder string, indentString string, ClassIdentifier string) error {
	NameSpace := component.NameSpace
	BaseName := component.BaseName
	LibraryName := component.LibraryName
	upperNameSpace := strings.ToUpper(NameSpace)

	for _, class := range component.Classes {
		switch strings.ToLower(class.ClassName) {
		case "fwd", "wrapper", "table":
			return fmt.Errorf("class \"%s\" clashes with a header name of the split C++ binding", class.ClassName)
		}
	}

	CPPTypesHeaderName := path.Join(outputFolder, BaseName+"_types.hpp")
	err := CreateCPPTypesHeader(component, CPPTypesHeaderName, false)
	if err != nil {
		return err
	}

	fwdHeaderName := BaseName + "_dynamic_fwd.hpp"
	wrapperHeaderName := BaseName + "_dynamic_wrapper.hpp"
	tableHeaderName := BaseName + "_dynamic_table.hpp"
	umbrellaHeaderName := BaseName + "_dynamic.hpp"

	// ------------------------------------------------------------------ forward declarations
	w, err := createCppSplitFile(path.Join(outputFolder, fwdHeaderName), indentString, component,
		fmt.Sprintf("This is an autogenerated C++-Header file with the forward declarations of the\n classes of %s. Include %s to call their methods.", LibraryName, umbrellaHeaderName))
	if err != nil {
		return err
	}
	w.Writeln("#ifndef __%s_CPPHEADER_SPLIT_FWD", upperNameSpace)
	w.Writeln("#define __%s_CPPHEADER_SPLIT_FWD", upperNameSpace)
	w.Writeln("")
	w.Writeln("#include \"%s_types.hpp\"", BaseName)
	w.Writeln("")
	w.Writeln("#include <memory>")
	w.Writeln("")
	writeSplitNamespaceOpen(w, NameSpace)
	buildBindingCPPAllForwardDeclarations(component, w, NameSpace, "C", ClassIdentifier)
	writeSplitNamespaceClose(w, NameSpace)
	w.Writeln("#endif // __%s_CPPHEADER_SPLIT_FWD", upperNameSpace)
	closeLanguageFile(w)

	// ------------------------------------------------------------------ wrapper class and shared helpers
	err = buildSplitWrapperHeader(component, outputFolder, indentString, ClassIdentifier, fwdHeaderName, wrapperHeaderName)
	if err != nil {
		return err
	}

	// ------------------------------------------------------------------ one header per class
	baseClass := component.baseClass()
	for _, class := range component.Classes {
		w, err := createCppSplitFile(path.Join(outputFolder, cppSplitBindingClassHeaderName(BaseName, class.ClassName)), indentString, component,
			fmt.Sprintf("This is an autogenerated C++-Header file with the declaration of class %s of %s.", class.ClassName, LibraryName))
		if err != nil {
			return err
		}
		guard := fmt.Sprintf("__%s_CPPHEADER_SPLIT_%s", upperNameSpace, strings.ToUpper(class.ClassName))
		w.Writeln("#ifndef %s", guard)
		w.Writeln("#define %s", guard)
		w.Writeln("")
		w.Writeln("#include \"%s\"", wrapperHeaderName)
		if !component.isBaseClass(class) {
			parentName := class.ParentClass
			if parentName == "" {
				parentName = baseClass.ClassName
			}
			w.Writeln("#include \"%s\"", cppSplitBindingClassHeaderName(BaseName, parentName))
		}
		w.Writeln("")
		writeSplitNamespaceOpen(w, NameSpace)
		err = writeClassDeclaration(w, component, class, "C", ClassIdentifier, NameSpace, BaseName, dynamicBindingSplit)
		if err != nil {
			return err
		}
		writeSplitNamespaceClose(w, NameSpace)
		w.Writeln("#endif // %s", guard)
		closeLanguageFile(w)
	}

	// ------------------------------------------------------------------ umbrella header
	w, err = createCppSplitFile(path.Join(outputFolder, umbrellaHeaderName), indentString, component,
		fmt.Sprintf("This is an autogenerated C++-Header file in order to allow an easy\n use of %s. It includes the declarations of all classes.", LibraryName))
	if err != nil {
		return err
	}
	w.Writeln("#ifndef __%s_CPPHEADER_SPLIT", upperNameSpace)
	w.Writeln("#define __%s_CPPHEADER_SPLIT", upperNameSpace)
	w.Writeln("")
	w.Writeln("#include \"%s\"", wrapperHeaderName)
	for _, class := range component.Classes {
		w.Writeln("#include \"%s\"", cppSplitBindingClassHeaderName(BaseName, class.ClassName))
	}
	w.Writeln("")
	w.Writeln("#endif // __%s_CPPHEADER_SPLIT", upperNameSpace)
	closeLanguageFile(w)

	// ------------------------------------------------------------------ function table, only needed by the sources
	w, err = createCppSplitFile(path.Join(outputFolder, tableHeaderName), indentString, component,
		fmt.Sprintf("This is an autogenerated C++-Header file with the function table of %s. Only the\n source files of the split binding include it.", LibraryName))
	if err != nil {
		return err
	}
	err = buildDynamicCCPPHeader(component, w, NameSpace, BaseName, true, true, false)
	if err != nil {
		return err
	}
	w.Writeln("#include \"%s\"", wrapperHeaderName)
	w.Writeln("")
	writeSplitNamespaceOpen(w, NameSpace)
	w.Writeln("struct C%sWrapper::sTable : public s%sDynamicWrapperTable {", ClassIdentifier, NameSpace)
	w.Writeln("};")
	writeSplitNamespaceClose(w, NameSpace)
	w.Writeln("#endif // __%s_DYNAMICHEADER_CPPTYPES", upperNameSpace)
	closeLanguageFile(w)

	// ------------------------------------------------------------------ source
	return buildSplitSource(component, outputFolder, indentString, ClassIdentifier, umbrellaHeaderName, tableHeaderName)
}

func buildSplitWrapperHeader(component ComponentDefinition, outputFolder string, indentString string, ClassIdentifier string, fwdHeaderName string, wrapperHeaderName string) error {
	NameSpace := component.NameSpace
	upperNameSpace := strings.ToUpper(NameSpace)
	cppClassPrefix := "C"
	cppBaseClassName := cppClassPrefix + ClassIdentifier + component.baseClass().ClassName
	wrapperName := cppClassPrefix + ClassIdentifier + "Wrapper"

	w, err := createCppSplitFile(path.Join(outputFolder, wrapperHeaderName), indentString, component,
		fmt.Sprintf("This is an autogenerated C++-Header file with the declaration of the wrapper class of %s.", component.LibraryName))
	if err != nil {
		return err
	}
	w.Writeln("#ifndef __%s_CPPHEADER_SPLIT_WRAPPER", upperNameSpace)
	w.Writeln("#define __%s_CPPHEADER_SPLIT_WRAPPER", upperNameSpace)
	w.Writeln("")
	w.Writeln("#include \"%s\"", fwdHeaderName)
	w.Writeln("")
	for _, subComponent := range component.ImportedComponentDefinitions {
		w.Writeln("#include \"%s_dynamic.hpp\"", subComponent.BaseName)
	}
	w.Writeln("")
	w.Writeln("#include <array>")
	w.Writeln("#include <string>")
	w.Writeln("#include <memory>")
	w.Writeln("#include <vector>")
	w.Writeln("#include <exception>")
	w.Writeln("")
	writeSplitNamespaceOpen(w, NameSpace)

	writeClassParamDefinition(w, NameSpace)
	w.Writeln("")
	writeExceptionClass(w, NameSpace, component.Errors)
	w.Writeln("")
	writeCPPInputVector(w, NameSpace, ClassIdentifier)
	w.Writeln("")

	w.Writeln("/*************************************************************************************************************************")
	w.Writeln(" Class %s ", wrapperName)
	w.Writeln("**************************************************************************************************************************/")
	w.Writeln("class %s {", wrapperName)
	w.Writeln("public:")
	w.Writeln("  explicit %s(void* pSymbolLookupMethod);", wrapperName)
	w.Writeln("  explicit %s(const std::string &sFileName);", wrapperName)
	w.Writeln("  static P%sWrapper loadLibrary(const std::string &sFileName);", ClassIdentifier)
	w.Writeln("  static P%sWrapper loadLibraryFromSymbolLookupMethod(void* pSymbolLookupMethod);", ClassIdentifier)
	w.Writeln("  ~%s();", wrapperName)
	w.Writeln("  ")
	if component.isMultiThreadedEnv() {
		w.Writeln("  void CheckError(%s * pBaseClass, %sResult nResult, bool unlockIfError = false);", cppBaseClassName, NameSpace)
	} else {
		w.Writeln("  void CheckError(%s * pBaseClass, %sResult nResult);", cppBaseClassName, NameSpace)
	}
	w.Writeln("")
	for _, method := range component.Global.Methods {
		err := writeDynamicCPPMethodDeclaration(method, w, NameSpace, ClassIdentifier, "Wrapper", dynamicBindingSplit)
		if err != nil {
			return err
		}
	}
	w.Writeln("")
	w.Writeln("  C%s* polymorphicFactory(%sHandle);", component.Global.BaseClassName, NameSpace)
	w.Writeln("")
	w.Writeln("private:")
	if len(component.ImportedComponentDefinitions) > 0 {
		w.Writeln("  // Injected Components")
		for _, subComponent := range component.ImportedComponentDefinitions {
			w.Writeln("  %s::PWrapper m_p%sWrapper;", subComponent.NameSpace, subComponent.NameSpace)
		}
		w.Writeln("")
	}
	w.Writeln("  %sResult checkBinaryVersion();", NameSpace)
	w.Writeln("")
	w.Writeln("  // The function table is only visible to the source files of the binding.")
	w.Writeln("  struct sTable;")
	w.Writeln("  std::unique_ptr<sTable> m_pTable;")
	w.Writeln("")
	for _, class := range component.Classes {
		w.Writeln("  friend class %s;", cppClassPrefix+ClassIdentifier+class.ClassName)
	}
	w.Writeln("};")
	writeSplitNamespaceClose(w, NameSpace)
	w.Writeln("#endif // __%s_CPPHEADER_SPLIT_WRAPPER", upperNameSpace)
	closeLanguageFile(w)
	return nil
}

func writeSplitSourcePrologue(w LanguageWriter, umbrellaHeaderName string, tableHeaderName string) {
	w.Writeln("#include \"%s\"", umbrellaHeaderName)
	w.Writeln("#include \"%s\"", tableHeaderName)
	w.Writeln("")
	w.Writeln("#ifdef _WIN32")
	w.Writeln("#include <windows.h>")
	w.Writeln("#else // _WIN32")
	w.Writeln("#include <dlfcn.h>")
	w.Writeln("#endif // _WIN32")
	w.Writeln("")
}

// writeSplitWrapperImplementation writes the function table handling, the life time handling, the error handling,
// the polymorphic factory and the global methods of the wrapper class.
func writeSplitWrapperImplementation(component ComponentDefinition, w LanguageWriter, ClassIdentifier string) error {
	NameSpace := component.NameSpace
	BaseName := component.BaseName
	cppClassPrefix := "C"
	cppBaseClassName := cppClassPrefix + ClassIdentifier + component.baseClass().ClassName
	wrapperName := cppClassPrefix + ClassIdentifier + "Wrapper"
	tableType := "s" + NameSpace + "DynamicWrapperTable"

	// function table handling
	w.Writeln("namespace {")
	w.Writeln("")
	w.Writeln("%sResult initWrapperTable(%s * pWrapperTable)", NameSpace, tableType)
	w.Writeln("{")
	w.AddIndentationLevel(1)
	buildDynamicCInitTableCode(component, w, NameSpace, BaseName, false)
	w.AddIndentationLevel(-1)
	w.Writeln("}")
	w.Writeln("")
	w.Writeln("%sResult releaseWrapperTable(%s * pWrapperTable)", NameSpace, tableType)
	w.Writeln("{")
	w.AddIndentationLevel(1)
	buildDynamicCReleaseTableCode(component, w, NameSpace, BaseName, "initWrapperTable", false)
	w.AddIndentationLevel(-1)
	w.Writeln("}")
	w.Writeln("")
	w.Writeln("%sResult loadWrapperTable(%s * pWrapperTable, const char * pLibraryFileName)", NameSpace, tableType)
	w.Writeln("{")
	w.AddIndentationLevel(1)
	buildDynamicCLoadTableCode(component, w, NameSpace, BaseName, false)
	w.AddIndentationLevel(-1)
	w.Writeln("}")
	w.Writeln("")
	w.Writeln("%sResult loadWrapperTableFromSymbolLookupMethod(%s * pWrapperTable, void* pSymbolLookupMethod)", NameSpace, tableType)
	w.Writeln("{")
	w.AddIndentationLevel(1)
	buildDynamicCLoadTableFromSymbolLookupMethodCode(component, w, NameSpace, BaseName, false)
	w.AddIndentationLevel(-1)
	w.Writeln("}")
	w.Writeln("")
	w.Writeln("} // anonymous namespace")
	w.Writeln("")

	// life time handling
	w.Writeln("%s::%s(void* pSymbolLookupMethod)", wrapperName, wrapperName)
	w.Writeln("  : m_pTable(new sTable())")
	w.Writeln("{")
	w.Writeln("  CheckError(nullptr, initWrapperTable(m_pTable.get()));")
	w.Writeln("  CheckError(nullptr, loadWrapperTableFromSymbolLookupMethod(m_pTable.get(), pSymbolLookupMethod));")
	w.Writeln("  ")
	w.Writeln("  CheckError(nullptr, checkBinaryVersion());")
	w.Writeln("}")
	w.Writeln("")
	w.Writeln("%s::%s(const std::string &sFileName)", wrapperName, wrapperName)
	w.Writeln("  : m_pTable(new sTable())")
	w.Writeln("{")
	w.Writeln("  CheckError(nullptr, initWrapperTable(m_pTable.get()));")
	w.Writeln("  CheckError(nullptr, loadWrapperTable(m_pTable.get(), sFileName.c_str()));")
	w.Writeln("  ")
	w.Writeln("  CheckError(nullptr, checkBinaryVersion());")
	w.Writeln("}")
	w.Writeln("")
	w.Writeln("P%sWrapper %s::loadLibrary(const std::string &sFileName)", ClassIdentifier, wrapperName)
	w.Writeln("{")
	w.Writeln("  return std::make_shared<%s>(sFileName);", wrapperName)
	w.Writeln("}")
	w.Writeln("")
	w.Writeln("P%sWrapper %s::loadLibraryFromSymbolLookupMethod(void* pSymbolLookupMethod)", ClassIdentifier, wrapperName)
	w.Writeln("{")
	w.Writeln("  return std::make_shared<%s>(pSymbolLookupMethod);", wrapperName)
	w.Writeln("}")
	w.Writeln("")
	w.Writeln("%s::~%s()", wrapperName, wrapperName)
	w.Writeln("{")
	w.Writeln("  if (m_pTable)")
	w.Writeln("    releaseWrapperTable(m_pTable.get());")
	w.Writeln("}")
	w.Writeln("")

	writeCheckBinaryVersion(w, NameSpace, component, wrapperName)
	w.Writeln("")

	writeCheckErrorImplementation(w, component.Global.ErrorMethod, ClassIdentifier, cppBaseClassName, NameSpace, component.isMultiThreadedEnv(), dynamicBindingSplit)
	w.Writeln("")

	writePolymorphicFactoryImplementation(w, component, NameSpace, cppClassPrefix, ClassIdentifier, true, false, dynamicBindingSplit)
	w.Writeln("")

	// global methods
	for _, method := range component.Global.Methods {
		isSpecialFunction, err := CheckHeaderSpecialFunction(method, component.Global)
		if err != nil {
			return err
		}

		implementationLines := buildInjectionImplementationLines(component, method, isSpecialFunction, NameSpace)

		err = writeDynamicCPPMethod(method, w, NameSpace, ClassIdentifier, "Wrapper", implementationLines, true, true, false, true, true, false, component.isMultiThreadedEnv(), eThreadSafetyNone, dynamicBindingSplit)
		if err != nil {
			return err
		}
	}
	return nil
}

// buildSplitSource writes the single source file of the split binding: the wrapper implementation and the
// methods of all classes.
func buildSplitSource(component ComponentDefinition, outputFolder string, indentString string, ClassIdentifier string, umbrellaHeaderName string, tableHeaderName string) error {
	NameSpace := component.NameSpace

	w, err := createCppSplitFile(path.Join(outputFolder, component.BaseName+"_dynamic.cpp"), indentString, component,
		fmt.Sprintf("This is an autogenerated C++ source file with the implementation of the classes of %s.", component.LibraryName))
	if err != nil {
		return err
	}
	writeSplitSourcePrologue(w, umbrellaHeaderName, tableHeaderName)
	writeSplitNamespaceOpen(w, NameSpace)

	err = writeSplitWrapperImplementation(component, w, ClassIdentifier)
	if err != nil {
		return err
	}

	for _, class := range component.Classes {
		cppClassName := "C" + ClassIdentifier + class.ClassName
		w.Writeln("  ")
		w.Writeln("  /**")
		w.Writeln("   * Method definitions for class %s", cppClassName)
		w.Writeln("   */")
		for _, method := range class.Methods {
			err := writeDynamicCPPMethod(method, w, NameSpace, ClassIdentifier, class.ClassName, make([]string, 0), false, true, false, true, true, false, component.isMultiThreadedEnv(), component.getRealThreadSafetyOption(&class), dynamicBindingSplit)
			if err != nil {
				return err
			}
		}
	}

	writeSplitNamespaceClose(w, NameSpace)
	closeLanguageFile(w)
	return nil
}
